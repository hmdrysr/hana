#!/usr/bin/env python3
"""Writes .github/workflows/unzip.yml, with tools/unpack.py copied inside it,
so the workflow works in a repo that has nothing else yet.
Run it after changing tools/unpack.py:   python3 tools/make_workflow.py
tools/selftest.py fails if the workflow is out of date."""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

HEAD = """# Unzip workflow. Upload a .zip to the top level of the repo (GitHub: Add file, then
# Upload files). This unpacks it into the repo, fills in the repo's own address,
# runs the checks, commits the result and starts the GitHub Pages deployment.
# Paste this file in by hand as .github/workflows/unzip.yml. It is generated by
# tools/make_workflow.py, so change the tools and regenerate it.
name: unzip
on:
  push:
    branches: [main]
    paths: ['*.zip']
  workflow_dispatch:
permissions:
  contents: write
  actions: write
concurrency:
  group: unzip
  cancel-in-progress: false
env:
  PYTHONDONTWRITEBYTECODE: "1"
jobs:
  unzip:
    runs-on: ubuntu-24.04
    steps:
      - uses: actions/checkout@v5
        with:
          ref: main
      - name: Write the unpack tool
        run: |
          mkdir -p "$RUNNER_TEMP/hana"
          cat > "$RUNNER_TEMP/hana/unpack.py" <<'HANA_UNPACK_EOF'
@@UNPACK@@
          HANA_UNPACK_EOF
      - name: Unpack every zip at the top level
        id: unpack
        run: |
          shopt -s nullglob
          zips=(*.zip)
          if [ ${#zips[@]} -eq 0 ]; then
            echo "No .zip at the top level of the repo. Nothing to do."
            echo "found=no" >> "$GITHUB_OUTPUT"
            exit 0
          fi
          echo "found=yes" >> "$GITHUB_OUTPUT"
          python3 "$RUNNER_TEMP/hana/unpack.py" --report "$RUNNER_TEMP/report.txt" "${zips[@]}"
          git rm -q --ignore-unmatch "${zips[@]}"
          rm -f "${zips[@]}"
          # Python cache folders never belong in the repo.
          git rm -r -q --cached --ignore-unmatch tools/__pycache__ || true
      - name: Fill in the repo address
        if: steps.unpack.outputs.found == 'yes'
        run: if [ -f tools/autofill.py ]; then python3 tools/autofill.py; fi
      - name: Check the repo (shown in the log, does not stop the commit)
        if: steps.unpack.outputs.found == 'yes'
        continue-on-error: true
        run: |
          if [ -f tools/check.py ]; then python3 tools/check.py; else echo "tools/check.py not found"; fi
      - name: Commit and push
        id: commit
        if: steps.unpack.outputs.found == 'yes'
        run: |
          git config user.name "github-actions[bot]"
          git config user.email "41898282+github-actions[bot]@users.noreply.github.com"
          find . -name __pycache__ -type d -prune -exec rm -rf {} +
          git add -A
          if git diff --cached --quiet; then
            echo "No changes to commit."
            echo "pushed=no" >> "$GITHUB_OUTPUT"
            exit 0
          fi
          git commit -q -m "Unpack zip" -m "$(cat "$RUNNER_TEMP/report.txt")"
          # Another upload may have landed while this ran: replay this commit on top of it.
          git pull --rebase -q origin main
          git push origin HEAD:main
          echo "pushed=yes" >> "$GITHUB_OUTPUT"
      - name: Start the GitHub Pages deployment
        # A push made by this workflow does not start other workflows, so start Pages here.
        if: steps.commit.outputs.pushed == 'yes' && hashFiles('.github/workflows/pages.yml') != ''
        env:
          GH_TOKEN: ${{ github.token }}
        run: gh workflow run pages.yml --ref main
"""


def indent(text, n=10):
    pad = " " * n
    return "\n".join((pad + line) if line else "" for line in text.rstrip("\n").split("\n"))


def render():
    return (HEAD.replace("@@UNPACK@@", indent((ROOT / "tools" / "unpack.py").read_text(encoding="utf-8")))
           )


if __name__ == "__main__":
    out = ROOT / ".github" / "workflows" / "unzip.yml"
    out.write_text(render(), encoding="utf-8")
    print("wrote", out)
